// Writes supabase/recipes-full-upsert.sql: an insert-or-update for every recipe in private/recipes-full.json
// into public.recipes_full. Safe to run in Supabase again; existing rows are replaced with the file's content.
// Run from the repo root: npm run build:recipe-sql
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'private', 'recipes-full.json');
const OUT = path.join(ROOT, 'supabase', 'recipes-full-upsert.sql');

const recipes = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
if (!Array.isArray(recipes) || !recipes.length) throw new Error('private/recipes-full.json must be a non-empty array');
const problems = [];
const ids = new Set();
for (const r of recipes) {
  if (!/^[a-z0-9-]{1,80}$/.test(r.id || '')) problems.push('bad slug: ' + r.id);
  if (ids.has(r.id)) problems.push('duplicate slug: ' + r.id);
  ids.add(r.id);
  if (!r.title) problems.push(r.id + ': no title');
}
if (problems.length) { console.error('Recipe data problems:\n- ' + problems.join('\n- ')); process.exit(1); }

// Dollar quoting with a tag that cannot appear in the JSON, so no escaping is needed.
const TAG = '$recipe$';
if (JSON.stringify(recipes).includes(TAG)) throw new Error('the dollar-quote tag appears in the data');
const rows = recipes.map(r => `  ('${r.id}', ${TAG}${JSON.stringify(r)}${TAG}::jsonb)`);
const sql = `-- Insert or update every recipe in public.recipes_full. Generated by scripts/build-recipe-sql.js.
-- Run in the Supabase SQL editor. Safe to run again. Needs the table from supabase/recipes-full.sql (run once).
insert into public.recipes_full (id, data) values
${rows.join(',\n')}
on conflict (id) do update set data = excluded.data;
`;
fs.writeFileSync(OUT, sql);
console.log('wrote', path.relative(ROOT, OUT), 'with', recipes.length, 'recipes');
